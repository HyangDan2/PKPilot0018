export const DICT: Record<Lang, Dict> = { en, ko };

export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Resolve a stored label: strings beginning with "@" are translation keys. */
export function resolveLabel(lang: Lang, label: string, vars?: Record<string, string | number>): string {
  if (label.startsWith('@')) return t(lang, label.slice(1), vars);
  return label;
}

